const esc = (t) => t.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const alt = (n) => esc(ALT[n])
const LI = 'https://www.linkedin.com/in/quang-minh-dinh-0b4380359/', GH = 'https://github.com/minh20003', LFR = 'https://github.com/minh20003/linguaflow-ai', LFD = 'https://c3-lingua-flow-217.dquangminh2003.id.vn', SFB = 'https://github.com/minh20003/SportFieldBookingApp', SFH = 'https://github.com/minh20003/htdocs'
// Layout constants (see NOTES.md): BP = <picture> breakpoint, FULL = width of every full-bleed image, HALF = pair segments.
// Pairs are exactly 50% + 50% with NO whitespace between the two anchors (they are written back to back below); the 4-unit gutter is baked into the half SVGs.
// So the pair spans exactly 100% and lines up with the 100% cards at every width.
// BP = 1011: GitHub keeps its ~256-296px profile sidebar beside the README from ~768px up, so the README column is only ~340..560px between 768 and 1011px;
// the 800-unit art would render at 0.4..0.7 there (13px text = 5..9px). Up to 1011px the 360-unit art is used (scale ~0.9..1.9), the 800-unit art from 1012px (column >= ~560px).
const BP = 1011, FULL = '100%', HALF = '50%'
// align="top" removes the baseline gap under inline images, so footer strips sit flush under their card
const pic = (n, alt, w = FULL, href) => {
  const p = `<picture><source media="(max-width: ${BP}px)" srcset="assets/${n}-m.svg"><img src="assets/${n}.svg" width="${w}" align="top" alt="${alt}"></picture>`
  return href ? `<a href="${href}">${p}</a>` : p
}
